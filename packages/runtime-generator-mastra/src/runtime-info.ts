      '// after the build, or a context-service from another release a *readiness* failure',
      '// instead of a Run that half-works.',
      '//',
      '// The blocks below are kept apart on purpose. Every check compares two of them, so a',
      '// passing verification is evidence that two documents agree — not a constant',
      '// agreeing with itself. Nothing here reads a clock, a random source or the',
      '// environment: the one timestamp the document carries comes from `ids.ts`.',
      '',
      "import { loadConfig } from './config.ts';",
      "import { nowIso } from './ids.ts';",
      "import { STATE_SCHEMA_VERSION, STATE_STORE_KIND } from './state-store.ts';",
      '',
      '// --- the wire shape (`runtime-info.schema.json`) ----------------------------',
      '',
      "/** `runtime-capabilities.schema.json#/$defs/Support`. */",
      "export type Support = 'native' | 'adapter' | 'degraded' | 'none';",
      '',
      '/** One `capability_details` entry: the level, plus what is lost when it is `degraded`. */',
      'export interface CapabilityNode {',
      '  support: Support;',
      '  limitations?: string[];',
      '}',
      '',
      '/** `<group>` and `<group>.<member>` → node (`runtime-capabilities.schema.json#/$defs/CapabilityDetails`). */',
      'export type CapabilityDetails = Record<string, CapabilityNode>;',
      '',
      '/** `runtime-profile.schema.json#/$defs/Licensing`, as the handshake reports it. */',
      'export interface Licensing {',
      "  runtime: 'Apache-2.0' | 'MIT' | 'Elastic-2.0' | 'other';",
      '  requiresLicenseKey: boolean;',
      '  egress: boolean;',
      '}',
      '',
      "export type StateStoreKind = 'sqlite' | 'libsql' | 'postgres';",
      "export type TopologyMode = 'split' | 'merged-container' | 'agent-server';",
      '',
      '/** `runtime-info.schema.json#/$defs/RuntimeDescriptor`. */',
      'export interface RuntimeDescriptor {',
      '  family: string;',
      "  language: 'typescript' | 'python';",
      '  version: string;',
      '  profile_digest: string;',
      '  generator_version: string;',
      '  state_store: StateStoreKind;',
      '  topology: TopologyMode;',
      '  licensing: Licensing;',
      '}',
      '',
      '/** The component names the schema enumerates; a name outside it is a contract violation. */',
      "export type ComponentName =",
      "  | 'runtime-app'",
      "  | 'runtime-state'",
      "  | 'mastra-app'",
      "  | 'mastra-state'",
      "  | 'context-service'",
      "  | 'graph-store'",
      "  | 'audit-store';",
      '',
      '/** `runtime-info.schema.json#/$defs/ComponentInfo`. */',
      'export interface ComponentInfo {',
      '  name: ComponentName;',
      '  version: string;',
      '  contract_version: string;',
      "  status: 'ready' | 'degraded' | 'starting' | 'failed';",
      '  schema_version?: string;',
      '}',
      '',
      '/** `runtime-info.schema.json#/$defs/Limits`. */',
      'export interface Limits {',
      '  max_nodes: number;',
      '  max_edges: number;',
      '  max_request_timeout_ms: number;',
      '  max_run_deadline_ms: number;',
      '}',
      '',
      '/**',
