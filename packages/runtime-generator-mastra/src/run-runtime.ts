/**
 * Emitters for the Run API's dependency-free runtime modules.
 *
 * Each module below is emitted text, not generator behaviour: the tree is the
 * deliverable, so these functions are the whole of what the customer receives.
 * They are kept out of `app.ts` because they are one concern — the Run service's
 * data plane — and because the emitted code is long enough to review on its own.
 *
 * The modules are dependency-free on purpose (Node built-ins only): the app's
 * package set is the Runtime Profile's, and the Profile pins no HTTP framework,
 * no SQL driver and no test library. `node:sqlite` is Node's own, `node:crypto` is
 * Node's own, and nothing here pulls a package the Profile does not describe.
 *
 * In dependency order — each module only imports the ones above it:
 *
 *   ids, canonical        identity, digests
 *   wire, errors, sse     the contract, the envelope, the event framing
 *   config, state-store   deployment configuration, persistence
 *   sync/migrate          the job entrypoint
 *   exec-context, client  per-call identity, the context-service seam
 *   roles, identity       the role matrix and the ES256 issuer (`identity.ts`)
 *   run-registry, router  the Run lifecycle and the HTTP surface
 *   run-service           capability → workflow, abort propagation
 */

const file = (path: string, content: string): GeneratedFile => ({
  path,
  mode: GENERATED_FILE_MODE,
  content,
});

/** `runtime/ids.ts` — the one place the app looks at a clock or at randomness. */
export function idsModule(generatorVersion: string): GeneratedFile {
  return file(
    'mastra-app/src/runtime/ids.ts',
    [
      generatedHeader(generatorVersion, 'contracts/schemas/common.schema.json (Ulid, RunId, TraceId)'),
      "import { randomBytes } from 'node:crypto';",
      '',
      '// A build may not read a clock or a random source (A11), but a *run* must: the',
      '// contract ids are ULIDs and trace ids are random. Keeping both here means the',
      "// rest of the tree never sees `Date` or `randomBytes`, and searching for either",
      '// finds every place the app is not a pure function.',
      '',
      "/** Crockford base32: the alphabet the contract's `Ulid` pattern uses. */",
      "const CROCKFORD = '0123456789ABCDEFGHJKMNPQRSTVWXYZ';",
      '',
      '/** `value` big-endian in `length` Crockford characters. */',
      'function encode(value: bigint, length: number): string {',
      '  let remaining = value;',
      "  let out = '';",
      '  for (let index = 0; index < length; index += 1) {',
      '    out = `${CROCKFORD[Number(remaining & 31n)]}${out}`;',
      '    remaining >>= 5n;',
      '  }',
      '  return out;',
      '}',
      '',
      '/**',
      ' * A 26-character ULID: 48-bit millisecond timestamp, then 80 bits of randomness.',
      ' * `now` is a parameter so a test can pin the time part and still see the contract',
      ' * pattern.',
      ' */',
      'export function ulid(now: number = Date.now()): string {',
      '  const time = BigInt(Math.trunc(now));',
      '  const randomness = BigInt(`0x${randomBytes(10).toString(\'hex\')}`);',
      '  return `${encode(time, 10)}${encode(randomness, 16)}`;',
      '}',
      '',
      '/** `run_<ulid>`, the only Run identifier the client API ever shows. */',
      'export function runId(): string {',
      '  return `run_${ulid()}`;',
      '}',
      '',
      '/** A W3C trace id: 16 random bytes, lowercase hex. */',
      'export function traceId(): string {',
      "  return randomBytes(16).toString('hex');",
      '}',
      '',
      '/** A W3C span id: 8 random bytes, lowercase hex. */',
      'export function spanId(): string {',
      "  return randomBytes(8).toString('hex');",
      '}',
      '',
      '/**',
      ' * The `traceparent` every context-service call carries. `sampled` is `01`: the',
      ' * audit trail does not sample, and a trace nobody keeps is a trace nobody reads.',
      ' */',
      'export function traceparent(trace: string, span: string = spanId()): string {',
      '  return `00-${trace}-${span}-01`;',
      '}',
      '',
      '/** RFC 3339, millisecond precision: the contract `Timestamp`. */',
      'export function nowIso(): string {',
      '  return new Date().toISOString();',
      '}',
      '',
      '/** Epoch seconds: the unit a JWT counts `iat` and `exp` in. */',
      'export function unixSeconds(now: number = Date.now()): number {',
      '  return Math.trunc(now / 1000);',
      '}',
      '',
    ].join('\n'),
  );
}

/** `runtime/canonical.ts` — stable JSON and the digest idempotency keys are scoped by. */
export function canonicalModule(generatorVersion: string): GeneratedFile {
  return file(
    'mastra-app/src/runtime/canonical.ts',
    [
      generatedHeader(generatorVersion, 'contracts/schemas/common.schema.json (Digest) + docs/runtime-contract.md §3.5'),
      "import { createHash } from 'node:crypto';",
      '',
      '// Two requests with the same JSON payload but a different key order are the same',
      '// request; two different payloads are not. That comparison needs one canonical',
      '// serialization, so idempotency digests do not depend on how a client happened to',
      '// build its object.',
      '',
      '/** JSON with object keys sorted by code unit, `undefined` members dropped. */',
      'export function canonicalJson(value: unknown): string {',
      "  if (value === null || value === undefined) return 'null';",
      '  if (typeof value === \'number\') return Number.isFinite(value) ? JSON.stringify(value) : \'null\';',
      "  if (typeof value !== 'object') {",
      '    const leaf = JSON.stringify(value);',
      "    return leaf === undefined ? 'null' : leaf;",
      '  }',
      '  if (Array.isArray(value)) {',
      '    return `[${value.map((entry) => canonicalJson(entry)).join(\',\')}]`;',
      '  }',
      '  const entries = Object.entries(value as Record<string, unknown>)',
      '    .filter(([, entry]) => entry !== undefined)',
      '    .sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0));',
      '  const body = entries.map(([key, entry]) => `${JSON.stringify(key)}:${canonicalJson(entry)}`).join(\',\');',
      '  return `{${body}}`;',
      '}',
      '',
      '/** `sha256:` over canonical JSON: the contract `Digest` shape. */',
      'export function sha256Digest(value: unknown): string {',
      "  return `sha256:${createHash('sha256').update(canonicalJson(value)).digest('hex')}`;",
      '}',
      '',
    ].join('\n'),
  );
}

