      '  }',
      '',
      '  /** Apply every migration not yet recorded; returns the ids applied by this call. */',
      '  migrate(now: string = nowIso()): string[] {',
      "    this.db.exec('CREATE TABLE IF NOT EXISTS schema_migrations (id TEXT PRIMARY KEY, version TEXT NOT NULL, applied_at TEXT NOT NULL)');",
      "    const recorded = this.db.prepare('SELECT id FROM schema_migrations WHERE id = ?');",
