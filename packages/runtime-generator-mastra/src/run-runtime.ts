      '   */',
      '  private async post(context: RunContext, path: string, body: unknown, options: CallOptions): Promise<unknown> {',
      '    const deadline = options.deadline ?? context.deadline;',
      '    const timeoutMs = options.timeoutMs ?? DEFAULT_REQUEST_TIMEOUT_MS;',
      '    const headers: Record<string, string> = {',
      '      ...JSON_HEADERS,',
