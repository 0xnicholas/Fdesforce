      "      return '';",
      '    }',
      '    const recorded = new Set(rows.map((row) => row.id));',
      '    for (const migration of MIGRATIONS) if (!recorded.has(migration.id)) return \'\';',
      '    return STATE_SCHEMA_VERSION;',
      '  }',
      '',
      '  /** Insert or update a Run. The registry row is the contract `RunStatus` the API returns. */',
      '  putRun(record: RunRecord): void {',
      '    this.writeRun(record);',
      '  }',
      '',
      '  private writeRun(record: RunRecord): void {',
      '    this.db',
      '      .prepare(',
      '        `INSERT INTO runs (run_id, trace_id, capability_id, status, started_at, finished_at, output_json, error_json)',
      '         VALUES (?, ?, ?, ?, ?, ?, ?, ?)',
      '         ON CONFLICT(run_id) DO UPDATE SET',
      '           status = excluded.status,',
      '           finished_at = excluded.finished_at,',
      '           output_json = excluded.output_json,',
      '           error_json = excluded.error_json`,',
      '      )',
      '      .run(',
      '        record.run_id,',
      '        record.trace_id,',
      '        record.capability_id,',
