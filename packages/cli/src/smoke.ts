import type { BuildFile } from './build.js';

/**
 * `deploy/smoke.mjs` — the post-deploy acceptance action a bundle ships (#34).
 *
 * After `docker compose up` there is one question the operator actually asks: does
 * this deployment serve a Run, and can the audit trail account for it? The script
 * answers it in five steps and stops at the first that does not hold:
 *
 * 1. `/healthz` — the process is alive;
 * 2. `/readyz` — the startup handshake passed (`degraded` serves and is reported);
 * 3. `/v1/runtime-info` — the deployment is the contract and service it claims;
 * 4. `POST /v1/runs` under an `Idempotency-Key` — a Run starts, replays under the
 *    same key, reaches a terminal state and records the Decision it wrote;
 * 5. `GET /v1/provenance/{decision_id}` — that Decision reads back with its PROV-O
 *    lineage and without a backend-internal name (C14).
 *
 * Two rules shape the file. It carries **no address and no credential**: endpoints
 * and the auditor's ExecutionContext arrive by flag or environment (§9.3), so the
 * same artifact is deployable to every customer. And it has **no dependencies**:
 * the bundle has no `npm install` step after a build, so the script uses `fetch`
 * and a handful of Node built-ins and nothing else. The content is a pure function
 * of the Spec (the default capability), so it is part of the bundle's address.
 */

export interface SmokeScriptInput {
  /** The capability the smoke starts unless `--capability` names another. */
  defaultCapability: string;
  builderVersion: string;
}

export const SMOKE_SCRIPT_PATH = 'deploy/smoke.mjs';
/** Executable: the shebang is there so the operator can run the file directly. */
export const SMOKE_SCRIPT_MODE = 0o755;

export function smokeScript(input: SmokeScriptInput): BuildFile {
  const body = [
    '#!/usr/bin/env node',
    `// fde bundle smoke — written by fde build ${input.builderVersion}; do not edit.`,
    '//',
    '// healthz -> readyz -> runtime-info -> POST /v1/runs -> provenance, in that',
    '// order, stopping at the first step that does not hold. Run it from the bundle',
    '// root after the deployment is up:',
    '//',
    '//   node deploy/smoke.mjs --base-url https://mastra.example.internal \\',
    '//     --context-service-url http://context-service:8011 \\',
    '//     --token "$FDE_SMOKE_TOKEN" --audit-token "$FDE_SMOKE_AUDIT_TOKEN"',
    '//',
    '// `--token` is the caller credential the Run API accepts; `--audit-token` is the',
    '// ExecutionContext that reads the audit trail, and falls back to `--token` when a',
    '// deployment accepts one for both. Flags fall back to FDE_SMOKE_BASE_URL,',
    '// FDE_SMOKE_CONTEXT_SERVICE_URL, FDE_SMOKE_TOKEN, FDE_SMOKE_AUDIT_TOKEN,',
    '// FDE_SMOKE_CAPABILITY and FDE_SMOKE_TIMEOUT. Exit codes:',
    '// 0 all steps passed, 1 a step failed, 2 the invocation is unusable.',
    '',
    "const DEFAULT_CAPABILITY = '" + input.defaultCapability + "';",
    "// The contract's Run statuses (`contracts/schemas/run.schema.json`). `succeeded`,",
    '// not `finished`: `run.finished` is an SSE event, and a smoke that waited for a',
    '// status the API never returns would poll until its own deadline.',
    "const TERMINAL = ['succeeded', 'failed', 'cancelled'];",
    'const POLL_INTERVAL_MS = 1000;',
    'const DEFAULT_TIMEOUT_MS = 300000;',
    "// C14: a provenance document carries stable ids, never how the audit store keeps",
    '// them. A name from this list in the answer is an internal id leaking out.',
    '// `chain_head` is deliberately absent: `ProvenanceResponse.verification.chain_head`',
    "// is a contract field — the digest of the verified audit chain, not a row id.",
    "const INTERNAL_NAMES = ['sqlite', 'rowid'];",
    '',
    'const USAGE = [',
    "  'usage: node deploy/smoke.mjs --base-url <url> --context-service-url <url> --token <jwt>',",
    "  '                              [--audit-token <jwt>] [--capability <id>] [--timeout <ms>] [--json]',",
    "  '',",
    "  'Steps: healthz, readyz, runtime-info, POST /v1/runs (+ idempotent replay),',",
    "  '       GET /v1/provenance/{decision_id}.',",
    "].join('\\n');",
    '',
    'function parseArgs(argv) {',
    '  const values = {};',
    '  for (let index = 0; index < argv.length; index += 1) {',
    '    const arg = argv[index];',
    "    if (arg === '--help' || arg === '-h') { values.help = true; continue; }",
    "    if (arg === '--json') { values.json = true; continue; }",
    "    if (!arg.startsWith('--')) throw new UsageError('unexpected argument ' + JSON.stringify(arg));",
    '    const name = arg.slice(2);',
    '    const value = argv[index + 1];',
    "    if (value === undefined || value.startsWith('--')) throw new UsageError('--' + name + ' needs a value');",
    '    values[name] = value;',
    '    index += 1;',
    '  }',
    '  return values;',
    '}',
    '',
    'class UsageError extends Error {}',
    '',
    '/** A step that did not hold: the operator gets the step, the reason and nothing else. */',
    'class SmokeFailure extends Error {',
    '  constructor(step, message) {',
    '    super(message);',
    '    this.step = step;',
    '  }',
    '}',
    '',
    'function hex(bytes) {',
    '  return Array.from(crypto.getRandomValues(new Uint8Array(bytes)), (byte) =>',
    '    byte.toString(16).padStart(2, \'0\'),',
    "  ).join('');",
    '}',
    '',
    '/** W3C trace context: the smoke is a trace root, so the Run it starts is traceable. */',
    'function traceparent() {',
    "  return '00-' + hex(16) + '-' + hex(8) + '-01';",
    '}',
    '',
    "const sleep = (ms) => new Promise((resolve) => { setTimeout(resolve, ms); });",
    '',
    '/** One request with a budget; a transport failure names the step it belonged to. */',
    'async function call(step, url, init, deadline) {',
    '  const budget = Math.max(1000, deadline - Date.now());',
    '  let response;',
    '  try {',
    '    response = await fetch(url, { ...init, signal: AbortSignal.timeout(budget) });',
    '  } catch (cause) {',
    "    throw new SmokeFailure(step, url + ' could not be reached: ' + (cause?.message ?? String(cause)));",
    '  }',
    '  const text = await response.text();',
    '  let body;',
    '  try {',
    '    body = text === \'\' ? undefined : JSON.parse(text);',
    '  } catch {',
    '    body = text;',
    '  }',
    '  return { status: response.status, body };',
    '}',
    '',
    '/** The reason a refusal names: the contract envelope, or whatever the deployment said. */',
    'function reasonOf(answer) {',
    '  const error = answer.body?.error;',
    '  const reasons = answer.body?.reasons;',
    '  const parts = [];',
    '  if (Array.isArray(reasons) && reasons.length > 0) parts.push(reasons.join(\', \'));',
    '  if (error?.message !== undefined) parts.push(error.message);',
    '  else if (error?.code !== undefined) parts.push(error.code);',
    '  else if (typeof answer.body === \'string\' && answer.body !== \'\') parts.push(answer.body.trim());',
    "  return parts.length === 0 ? '' : ': ' + parts.join(' — ');",
    '}',
    '',
    'async function main() {',
    '  let args;',
    '  try {',
    '    args = parseArgs(process.argv.slice(2));',
    '  } catch (cause) {',
    '    process.stderr.write(\'smoke: \' + cause.message + \'\\n\' + USAGE + \'\\n\');',
    '    return 2;',
    '  }',
    '  if (args.help === true) {',
    '    process.stdout.write(USAGE + \'\\n\');',
    '    return 0;',
    '  }',
    '',
    '  const baseUrl = args[\'base-url\'] ?? process.env.FDE_SMOKE_BASE_URL;',
    '  const contextServiceUrl = args[\'context-service-url\'] ?? process.env.FDE_SMOKE_CONTEXT_SERVICE_URL;',
    '  const token = args[\'token\'] ?? process.env.FDE_SMOKE_TOKEN;',
    "  const auditToken = args['audit-token'] ?? process.env.FDE_SMOKE_AUDIT_TOKEN ?? token;",
    '  const capability = args[\'capability\'] ?? process.env.FDE_SMOKE_CAPABILITY ?? DEFAULT_CAPABILITY;',
    "  const timeoutMs = Number(args['timeout'] ?? process.env.FDE_SMOKE_TIMEOUT ?? DEFAULT_TIMEOUT_MS);",
    '  const json = args.json === true;',
    '',
    '  const missing = [];',
    "  if (baseUrl === undefined) missing.push('--base-url (FDE_SMOKE_BASE_URL)');",
    "  if (contextServiceUrl === undefined) missing.push('--context-service-url (FDE_SMOKE_CONTEXT_SERVICE_URL)');",
    "  if (token === undefined) missing.push('--token (FDE_SMOKE_TOKEN)');",
    "  if (capability === '') missing.push('--capability (FDE_SMOKE_CAPABILITY)');",
    '  if (missing.length > 0) {',
    "    process.stderr.write('smoke: missing ' + missing.join(', ') + '\\n' + USAGE + '\\n');",
    '    return 2;',
    '  }',
    '  if (!Number.isFinite(timeoutMs) || timeoutMs <= 0) {',
    "    process.stderr.write('smoke: --timeout must be a positive number of milliseconds\\n');",
    '    return 2;',
    '  }',
    '',
    '  const deadline = Date.now() + timeoutMs;',
    '  const steps = [];',
    '  const warnings = [];',
    '  const record = {};',
    '',
    '  const pass = (step, detail) => {',
    "    steps.push({ step, status: 'passed', ...(detail === undefined ? {} : { detail }) });",
    '    if (!json) process.stdout.write(step + \' ok\' + (detail === undefined ? \'\' : \' — \' + detail) + \'\\n\');',
    '  };',
    '  const warn = (step, message) => {',
    "    warnings.push({ step, message });",
    "    steps.push({ step, status: 'warned', detail: message });",
    "    if (!json) process.stderr.write('warning[' + step + '] ' + message + '\\n');",
    '  };',
    '',
    '  try {',
    '    // 1. Liveness: the process is up. Never 503, so a non-200 is the deployment.',
    "    const health = await call('healthz', baseUrl + '/healthz', {}, deadline);",
    "    if (health.status !== 200) throw new SmokeFailure('healthz', 'GET /healthz answered ' + health.status + reasonOf(health));",
    "    pass('healthz');",
    '',
    '    // 2. Readiness: the handshake passed. `degraded` serves traffic and is reported,',
    '    //    `not_ready` is a deployment that must not be sent any (§9.2).',
    "    const ready = await call('readyz', baseUrl + '/readyz', {}, deadline);",
    "    if (ready.status === 503) throw new SmokeFailure('readyz', 'the deployment is not ready' + reasonOf(ready));",
    "    if (ready.status !== 200) throw new SmokeFailure('readyz', 'GET /readyz answered ' + ready.status + reasonOf(ready));",
    "    const readiness = ready.body?.status;",
    "    if (readiness !== 'ready' && readiness !== 'degraded') {",
    "      throw new SmokeFailure('readyz', 'GET /readyz answered ' + readiness + ', which the contract does not define');",
    '    }',
    "    if (readiness === 'degraded') warn('readyz', 'serving degraded' + reasonOf(ready));",
    "    else pass('readyz');",
    '',
    '    // 3. The handshake the customer reads: contract major, service identity, and the',
    '    //    platform peer in the aggregate.',
    "    const info = await call('runtime-info', baseUrl + '/v1/runtime-info', {}, deadline);",
    "    if (info.status !== 200) throw new SmokeFailure('runtime-info', 'GET /v1/runtime-info answered ' + info.status + reasonOf(info));",
    '    // `contract_version` is the bare semver the wire carries; the major line is',
    "    // `fde.runtime/v1`, and a deployment on another major is not this client's peer.",
    '    const contractVersion = String(info.body?.contract_version ?? \'\');',
    "    const major = contractVersion.split('.')[0];",
    "    if (!/^[0-9]+\\.[0-9]+\\.[0-9]+$/.test(contractVersion) || major !== '1') {",
    "      throw new SmokeFailure('runtime-info', 'contract_version ' + JSON.stringify(contractVersion) + ' is not fde.runtime/v1');",
    '    }',
    "    if (info.body?.service !== 'runtime-app') {",
    "      throw new SmokeFailure('runtime-info', 'the deployment reports service ' + JSON.stringify(info.body?.service) + ', not runtime-app');",
    '    }',
    '    const components = Array.isArray(info.body?.components) ? info.body.components : [];',
    "    const peer = components.find((component) => component?.name === 'context-service');",
    '    if (peer === undefined) {',
    "      throw new SmokeFailure('runtime-info', 'the aggregate lists no context-service component; the bundle is not the split topology');",
    '    }',
    "    if (peer.status !== 'ready') warn('runtime-info', 'context-service reports ' + peer.status);",
    "    else pass('runtime-info', contractVersion);",
    '',
    '    // 4. A Run, replayed under the same key, then read back to a terminal state.',
    "    const idempotencyKey = 'smoke-' + crypto.randomUUID();",
    '    const request = {',
    '      capability_id: capability,',
    "      input: { query: 'fde smoke: read-only triage' },",
    '    };',
    '    // The Run API is authenticated (`contracts/runtime-api-v1.openapi.yaml`): the',
    '    // caller presents its credential on every Run call, so a deployment that',
    '    // stopped checking is not mistaken for the contract.',
    '    const headers = {',
    "      'content-type': 'application/json',",
    "      'idempotency-key': idempotencyKey,",
    '      traceparent: traceparent(),',
    "      authorization: 'Bearer ' + token,",
    '    };',
    "    const created = await call('run', baseUrl + '/v1/runs', {",
    "      method: 'POST',",
    '      headers,',
    '      body: JSON.stringify(request),',
    '    }, deadline);',
    "    if (created.status !== 201) throw new SmokeFailure('run', 'POST /v1/runs answered ' + created.status + reasonOf(created));",
    '    const runId = created.body?.run_id;',
    "    if (typeof runId !== 'string' || runId === '') throw new SmokeFailure('run', 'POST /v1/runs returned no run_id');",
    '    record.run_id = runId;',
    '    record.trace_id = created.body?.trace_id;',
    '',
    "    const replay = await call('run', baseUrl + '/v1/runs', {",
    "      method: 'POST',",
    '      headers,',
    '      body: JSON.stringify(request),',
    '    }, deadline);',
    '    if (replay.status !== 201 || replay.body?.run_id !== runId) {',
    "      throw new SmokeFailure('run', 'the same Idempotency-Key did not replay the same Run (answered ' + replay.status + ')');",
    '    }',
    '',
    '    let status;',
    '    for (;;) {',
    "      const polled = await call('run', baseUrl + '/v1/runs/' + encodeURIComponent(runId), { headers: { authorization: 'Bearer ' + token } }, deadline);",
    "      if (polled.status !== 200) throw new SmokeFailure('run', 'GET /v1/runs/' + runId + ' answered ' + polled.status + reasonOf(polled));",
    '      status = polled.body;',
    '      if (TERMINAL.includes(status?.status)) break;',
    '      if (Date.now() >= deadline) {',
    "        throw new SmokeFailure('run', 'Run ' + runId + ' was still ' + status?.status + ' after ' + timeoutMs + 'ms');",
    '      }',
    '      await sleep(POLL_INTERVAL_MS);',
    '    }',
    '    const decisions = Array.isArray(status.decisions) ? status.decisions : [];',
    '    const failure = status.error?.message ?? status.error?.code;',
    '    if (decisions.length === 0) {',
    "      throw new SmokeFailure('run', 'Run ' + runId + ' ended ' + status.status + (failure === undefined ? '' : ' (' + failure + ')') + '; no Decision was written, so there is no provenance to read back (§11.1)');",
    '    }',
    "    if (status.status !== 'succeeded') {",
    "      throw new SmokeFailure('run', 'Run ' + runId + ' ended ' + status.status + (failure === undefined ? '' : ' (' + failure + ')') + '; the smoke Run must succeed');",
    '    }',
    '    record.decision_id = decisions[0];',
    "    pass('run', runId);",
    '',
    '    // 5. The audit trail behind that Run: the Decision and its PROV-O lineage, with',
    '    //    no backend-internal name in the answer (C14).',
    "    const decisionId = decisions[0];",
    '    const provenance = await call(',
    "      'provenance',",
    "      contextServiceUrl + '/v1/provenance/' + encodeURIComponent(decisionId),",
    '      {',
    "        headers: { authorization: 'Bearer ' + auditToken, traceparent: traceparent() },",
    '      },',
    '      deadline,',
    '    );',
    '    if (provenance.status !== 200) {',
    "      throw new SmokeFailure('provenance', 'GET /v1/provenance/' + decisionId + ' answered ' + provenance.status + reasonOf(provenance));",
    '    }',
    '    if (provenance.body?.decision_id !== decisionId) {',
    "      throw new SmokeFailure('provenance', 'the document names ' + JSON.stringify(provenance.body?.decision_id) + ', not ' + decisionId);",
    '    }',
    '    if (provenance.body?.prov_o === undefined) {',
    "      throw new SmokeFailure('provenance', 'the document carries no PROV-O lineage');",
    '    }',
    '    const serialized = JSON.stringify(provenance.body);',
    '    for (const name of INTERNAL_NAMES) {',
    '      if (serialized.includes(name)) {',
    "        throw new SmokeFailure('provenance', 'the document leaks the backend-internal name ' + JSON.stringify(name) + ' (C14)');",
    '      }',
    '    }',
    "    pass('provenance', decisionId);",
    '  } catch (cause) {',
    '    const failure =',
    '      cause instanceof SmokeFailure',
    '        ? cause',
    "        : new SmokeFailure('smoke', cause instanceof Error ? cause.message : String(cause));",
    '    const errors = [{ step: failure.step, message: failure.message }];',
    '    if (json) {',
    '      process.stdout.write(',
    '        JSON.stringify(',
    '          {',
    "            script: 'smoke',",
    '            ok: false,',
    '            base_url: baseUrl,',
    '            context_service_url: contextServiceUrl,',
    '            capability_id: capability,',
    '            steps,',
    '            warnings,',
    '            errors,',
    '            ...record,',
    '          },',
    '          null,',
    '          2,',
    '        ) + \'\\n\',',
    '      );',
    '    } else {',
    "      process.stderr.write('error[' + failure.step + '] ' + failure.message + '\\n');",
    "      process.stdout.write('smoke: ' + steps.filter((step) => step.status === 'passed').length + ' passed, 1 failed\\n');",
    '    }',
    '    return 1;',
    '  }',
    '',
    '  if (json) {',
    '    process.stdout.write(',
    '      JSON.stringify(',
    '        {',
    "          script: 'smoke',",
    '          ok: true,',
    '          base_url: baseUrl,',
    '          context_service_url: contextServiceUrl,',
    '          capability_id: capability,',
    '          steps,',
    '          warnings,',
    '          errors: [],',
    '          ...record,',
    '        },',
    '        null,',
    '        2,',
    '      ) + \'\\n\',',
    '    );',
    '  } else {',
    '    process.stdout.write(',
    "      'smoke: ' + steps.filter((step) => step.status === 'passed').length + ' passed' + (warnings.length === 0 ? '' : ', ' + warnings.length + ' warning(s)') + '\\n',",
    '    );',
    '  }',
    '  return 0;',
    '}',
    '',
    'process.exitCode = await main();',
    '',
  ].join('\n');

  return { path: SMOKE_SCRIPT_PATH, content: body, mode: SMOKE_SCRIPT_MODE };
}
